/* ---------- engine ---------- */
function rmCost(p, RM){
  return p.cs_rock*RM.rock + p.cs_nh3*RM.nh3 + p.s_total*RM.sulphur
    + p.cs_borax*RM.borax + p.cs_zno*RM.zno + p.cs_cuso4*RM.cuso4
    + p.cs_kcl*RM.kcl + p.cs_sam*RM.sam + p.cs_caso4*RM.caso4
    + p.cs_caco3*RM.caco3 + p.cs_gypse*RM.gypse;
}
function refMargin(ref, RM, refPrice){ return refPrice - rmCost(REF_PROD[ref], RM); }
function cgmEq(p, price, rmc, ref){ return (price - rmc) * REF_ACP[ref] / p.cs_acp; }
function floorPrice(p, rmc, ref, RM, refPrice){ return rmc + refMargin(ref,RM,refPrice)/REF_ACP[ref]*p.cs_acp; }
function mcv(p, price, rmc){ return (price - rmc - p.variable_cost_total) / p.cs_acp; }
function nutrientPrice(p, ref, refPrice){ return refPrice / REF_NUT[ref] * p.nutrient_total; }

function compute(){
  const p = PRODUCTS[state.idx];
  const RM = state.rm;
  const ref = state.ref;
  const refPrice = ref==='TSP' ? state.refprice.tsp : state.refprice.dap;
  const rmc = rmCost(p, RM);
  const cgmRef = refMargin(ref, RM, refPrice);
  const price = state.price;
  const floor = floorPrice(p, rmc, ref, RM, refPrice);
  const nutri = nutrientPrice(p, ref, refPrice);
  return {
    p, ref, refPrice, rmc, cgmRef,
    sc0: { price, cgm: cgmEq(p, price, rmc, ref), mcv: mcv(p, price, rmc) },
    sc1: { price: floor, cgm: cgmRef, mcv: mcv(p, floor, rmc) },
    sc2: { price: nutri, cgm: cgmEq(p, nutri, rmc, ref), mcv: mcv(p, nutri, rmc) }
  };
}

