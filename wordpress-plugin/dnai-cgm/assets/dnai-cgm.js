async function chatSend(text){
  if(!text || !window.DNAI_CGM || !DNAI_CGM.rest){ return; }
  chatPush('user', text.replace(/</g,'&lt;'));
  chatHist.push({role:'user',content:text});
  const thinking=chatPush('bot', '<span class="cgm-typing">DeepSeek analyse…</span>');
  try{
    const res=await fetch(DNAI_CGM.rest+'/chat',{
      method:'POST',
      headers:{'Content-Type':'application/json','X-WP-Nonce':DNAI_CGM.nonce},
      body:JSON.stringify({ message:text, history:chatHist.slice(-4), catalog:chatCatalog(text), state:chatStateSummary() })
    });
    const data=await res.json();
    if(!res.ok || data.error){ thinking.innerHTML='⚠️ '+((data&&data.error)||('Erreur '+res.status)); return; }
    const act=parseAction(data.reply);
    if(!act){ thinking.innerHTML='⚠️ Réponse du modèle illisible. Reformulez la demande.'; return; }
    if(act.clarify){ thinking.innerHTML='❓ '+String(act.clarify).replace(/</g,'&lt;'); chatHist.push({role:'assistant',content:act.clarify}); return; }
    if(act.intent==='smalltalk'){ thinking.innerHTML=(act.preface||'Je suis le copilote CGM : demandez-moi un produit, un prix, une comparaison ou une sensibilité.').replace(/</g,'&lt;'); return; }
    applyAction(act);
    if(['compute','set','explain'].includes(act.intent)){
      const rr=compute();
      thinking.classList.toggle('warn', rr.sc0.cgm < rr.cgmRef-1e-6);
    }
    const pre=act.preface?('<div class="cgm-pre">'+String(act.preface).replace(/</g,'&lt;')+'</div>'):'';
    const ans=chatAnswer(act);
    thinking.innerHTML=pre+ans;
    chatHist.push({role:'assistant',content:'(action appliquée : '+(act.intent||'compute')+')'});
  }catch(e){
    thinking.innerHTML='⚠️ Réseau indisponible : '+e.message;
  }
}

