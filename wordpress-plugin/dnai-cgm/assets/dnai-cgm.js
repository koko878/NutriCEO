const RM_KEYS = ['rock','nh3','sulphur','kcl','sam','acs','borax','zno','cuso4','caso4','caco3','gypse'];

function cgmNorm(s){ return (s||'').toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g,''); }
function cgmTokens(s){ return cgmNorm(s).match(/[a-z0-9\-]+/g) || []; }

/* Resolve the product locally so we only send a few candidates (not the 141
   products) to the model — critical for prefill speed on CPU. */
function chatCandidates(message){
  const toks = cgmTokens(message).filter(t=>t.length>=2 && !['les','des','que','est','pour','avec','quel','quelle','prix','marge','le','la'].includes(t));
  if(!toks.length) return [];
  const scored = PRODUCTS.map((p,i)=>{
    const hay = cgmNorm(p.product+' '+p.line+' '+p.family);
    let s=0; toks.forEach(t=>{ if(hay.indexOf(t)>=0) s += (t.length>=4?2:1); });
    return {i,p,s};
  }).filter(x=>x.s>0).sort((a,b)=>b.s-a.s);
  return scored.slice(0,12);
}
function chatCatalog(message){
  const c = chatCandidates(message);
  if(!c.length) return '(aucun produit identifié dans la demande — mets product_index=null, ou garde le produit courant si la demande porte sur lui)';
  return c.map(x=>`#${x.i} ${x.p.product} — ${x.p.line} [${x.p.family}]`).join('\n');
}
function chatStateSummary(){
  const p=PRODUCTS[state.idx];
  return `produit=#${state.idx} ${p.product} — ${p.line} | référence=${state.ref} | prix=${Math.round(state.price)} | soufre=${state.rm.sulphur} | nh3=${state.rm.nh3} | rock=${state.rm.rock}`;
}

/* Tolerant JSON extraction: strip code fences, grab first {...last }. */
function parseAction(raw){
  if(!raw) return null;
  let t=String(raw).trim();
  t=t.replace(/```(?:json)?/gi,'').replace(/```/g,'').trim();
  const a=t.indexOf('{'), b=t.lastIndexOf('}');
  if(a<0||b<0||b<a) return null;
  try{ return JSON.parse(t.slice(a,b+1)); }catch(e){ return null; }
}

function applyAction(act){
  if(act.product_index!=null && PRODUCTS[act.product_index]){
    state.idx=act.product_index;
    state.ref=guessRef(PRODUCTS[state.idx]);
    if(act.price==null){
      const rp=state.ref==='TSP'?state.refprice.tsp:state.refprice.dap;
      state.price=Math.round(nutrientPrice(PRODUCTS[state.idx], state.ref, rp));
    }
  }
  if(act.ref==='DAP'||act.ref==='TSP') state.ref=act.ref;
  if(act.rm && typeof act.rm==='object'){
    RM_KEYS.forEach(k=>{ if(typeof act.rm[k]==='number') state.rm[k]=act.rm[k]; });
  }
  if(act.refprice && typeof act.refprice==='object'){
    if(typeof act.refprice.dap==='number') state.refprice.dap=act.refprice.dap;
    if(typeof act.refprice.tsp==='number') state.refprice.tsp=act.refprice.tsp;
  }
  if(act.sens && typeof act.sens==='object'){
    if(typeof act.sens.nh3==='number') state.sens.nh3=act.sens.nh3;
    if(typeof act.sens.sulphur==='number') state.sens.sulphur=act.sens.sulphur;
  }
  if(typeof act.price==='number') state.price=act.price;
  syncInputs(); render();
}

/* Build the factual answer from compute() — never from the model. */
function chatAnswer(act){
  const r=compute();
  const ok=r.sc0.cgm>=r.cgmRef-1e-6;
  if(act.intent==='compare'){
    const rows=PRODUCTS.map((p,i)=>{
      const rmc=rmCost(p,state.rm);
      const nutri=nutrientPrice(p,state.ref,state.ref==='TSP'?state.refprice.tsp:state.refprice.dap);
      return {p,i,cgm:cgmEq(p,nutri,rmc,state.ref)};
    }).sort((a,b)=>b.cgm-a.cgm);
    const top=rows.slice(0,3).map(x=>`• <b>${x.p.product} — ${x.p.line}</b> : CGM ${state.ref} Eq ${f(x.cgm,0)} $/t`).join('<br>');
    const low=rows.slice(-3).reverse().map(x=>`• <b>${x.p.product} — ${x.p.line}</b> : CGM ${state.ref} Eq ${f(x.cgm,0)} $/t`).join('<br>');
    return `<b>Créateurs de valeur</b> (prix valeur-nutriments, réf. ${state.ref}, marge réf. ${f(r.cgmRef,0)} $/t) :<br>${top}<br><br><b>Les plus sous-pricés</b> :<br>${low}`;
  }
  if(act.intent==='sensitivity'){
    const RM2=Object.assign({},state.rm);
    RM2.nh3=state.rm.nh3*(1+state.sens.nh3/100);
    RM2.sulphur=state.rm.sulphur*(1+state.sens.sulphur/100);
    const rmc2=rmCost(r.p,RM2);
    const cgm2=cgmEq(r.p,r.sc0.price,rmc2,state.ref);
    const impNh3=r.p.cs_nh3*(RM2.nh3-state.rm.nh3), impS=r.p.s_total*(RM2.sulphur-state.rm.sulphur);
    const driver=Math.abs(impS)>=Math.abs(impNh3)?'Soufre':'NH3';
    return `Avec +${f(state.sens.nh3,0)} % NH3 et +${f(state.sens.sulphur,0)} % Soufre :<br>`+
      `• Coût MP : ${f(r.rmc,1)} → <b>${f(rmc2,1)} $/t</b> (+${f(rmc2-r.rmc,1)})<br>`+
      `• CGM ${state.ref} Eq : ${f(r.sc0.cgm,0)} → <b>${f(cgm2,0)} $/t</b> (${f(cgm2-r.sc0.cgm,0)})<br>`+
      `Driver principal : <b>${driver}</b> (${f(driver==='Soufre'?impS:impNh3,1)} $/t).`;
  }
  // compute / set / explain / default
  return `<b>${r.p.product} — ${r.p.line}</b> · réf. ${state.ref}<br>`+
    `• Prix : <b>${f(r.sc0.price,0)} $/t</b><br>`+
    `• Coût MP : ${f(r.rmc,1)} $/t<br>`+
    `• CGM ${state.ref} Eq : <b>${f(r.sc0.cgm,0)} $/t</b> — marge réf. ${f(r.cgmRef,0)} $/t → ${ok?'✅ marge préservée':'⚠️ sous-pricé'}<br>`+
    `• MCV/t P₂O₅ : ${f(r.sc0.mcv,0)}<br>`+
    `• Prix plancher iso-marge (Sc1) : <b>${f(r.sc1.price,0)} $/t</b> · Prix valeur-nutriments (Sc2) : <b>${f(r.sc2.price,0)} $/t</b>`+
    (ok?'':`<br>👉 Il faudrait viser au moins le prix plancher de <b>${f(r.sc1.price,0)} $/t</b>.`);
}

